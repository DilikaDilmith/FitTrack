/**
 * Returns a high-definition image URL for any exercise by its NAME.
 * 1. Exact match in catalog
 * 2. Normalized lowercase alphanumeric match
 * 3. Keyword / movement pattern match
 * 4. Category fallback
 * 5. General fitness fallback
 */
export const getExerciseImage = (exerciseName, categoryName = '') => {
  if (!exerciseName) {
    const catKey = (categoryName || '').toLowerCase().trim();
    return CATEGORY_FALLBACK_IMAGES[catKey] || CATEGORY_FALLBACK_IMAGES.default;
  }

  const raw = String(exerciseName).toLowerCase().trim();
  const normalized = raw.replace(/[-_]/g, ' ').replace(/\s+/g, ' ');

  // 1. Direct match with raw
  if (EXERCISE_IMAGES[raw]) {
    return EXERCISE_IMAGES[raw];
  }

  // 2. Direct match with normalized
  if (EXERCISE_IMAGES[normalized]) {
    return EXERCISE_IMAGES[normalized];
  }

  // 3. Keyword matching
  for (const item of KEYWORD_MATCHES) {
    if (item.keywords.some((kw) => normalized.includes(kw))) {
      return item.image;
    }
  }

  // 4. Category match
  const catKey = (categoryName || '').toLowerCase().trim();
  if (CATEGORY_FALLBACK_IMAGES[catKey]) {
    return CATEGORY_FALLBACK_IMAGES[catKey];
  }

  return CATEGORY_FALLBACK_IMAGES.default;
};
